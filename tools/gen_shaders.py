#!/usr/bin/env python3
"""Compiles every shader with dxc and writes build/gen/*.h (byte arrays, the coverage table and
the embedded default config).

usage: gen_shaders.py <dxc dir> <project dir>
"""
import os
import subprocess
import sys

DXC_DIR, ROOT = sys.argv[1], sys.argv[2]
GEN = os.path.join(ROOT, "build", "gen")

# coverage variants: (name, game PS hash, defines)
VARIANTS = [
    ("base", 0x23568b87da57f655, []),
    ("dissolve", 0xad72537bdaf26928, ["DISSOLVE=1"]),
    ("fade", 0xc9c37ca4835cb163, ["FADE=1"]),
    ("dissolve_fade", 0xd6fb2e5e5c795ce9, ["DISSOLVE=1", "FADE=1"]),
]
SHARPEN_THRESHOLDS = [0.2, 0.3, 0.4, 0.5]
SHARPEN_WIDTHS = [1.0, 1.5, 2.0, 3.0]
COMPUTE = ["banner", "resolve", "resolve_tensor", "area_h", "area", "usm", "nn_bbox", "nn_prep", "nn_conv", "nn_pool", "nn_apply",
           "mirror_copy"]
# 16-bit math variants: (output name, source, profile, extra dxc arguments)
COMPUTE16 = [("nn_conv16", "nn_conv", "cs_6_4", ["-enable-16bit-types", "-D", "HALF=1"])]
GRAPHICS = [("imgui_vs", "vs_6_0"), ("imgui_ps", "ps_6_0")]   # overlay UI


def compile_shader(name, profile, hlsl, defines=(), args=()):
    out = os.path.join(GEN, name + ".cso")
    cmd = [os.path.join(DXC_DIR, "bin", "dxc"), "-T", profile, "-E", "main", "-O3", "-Fo", out, hlsl] + list(args)
    for d in defines:
        cmd += ["-D", d]
    env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(DXC_DIR, "lib"))
    subprocess.run(cmd, check=True, env=env)
    return open(out, "rb").read()


def array(name, data):
    body = ",".join(str(b) for b in data)
    return "static const unsigned char %s[] = {%s};\n" % (name, body)


def main():
    os.makedirs(GEN, exist_ok=True)
    shaders = os.path.join(ROOT, "shaders")

    for name in COMPUTE:
        data = compile_shader(name, "cs_6_0", os.path.join(shaders, name + ".hlsl"))
        with open(os.path.join(GEN, name + "_cso.h"), "w") as f:
            f.write("// generated from shaders/%s.hlsl\n" % name)
            f.write(array("k%sCso" % name.capitalize(), data))

    for name, source, profile, args in COMPUTE16:
        data = compile_shader(name, profile, os.path.join(shaders, source + ".hlsl"), args=args)
        with open(os.path.join(GEN, name + "_cso.h"), "w") as f:
            f.write("// generated from shaders/%s.hlsl (16-bit math)\n" % source)
            f.write(array("k%sCso" % name.capitalize(), data))

    for name, profile in GRAPHICS:
        data = compile_shader(name, profile, os.path.join(shaders, name + ".hlsl"))
        with open(os.path.join(GEN, name + "_cso.h"), "w") as f:
            f.write("// generated from shaders/%s.hlsl\n" % name)
            f.write(array("k%sCso" % name.capitalize(), data))

    cov_hlsl = os.path.join(shaders, "hair_coverage.hlsl")
    rows = []
    with open(os.path.join(GEN, "coverage_table.h"), "w") as f:
        f.write("// generated by tools/gen_shaders.py from shaders/hair_coverage.hlsl\n#pragma once\n\n")
        for vname, vhash, vdefs in VARIANTS:
            ident = "kCov_%s_raw" % vname
            f.write(array(ident, compile_shader("cov_%s_raw" % vname, "ps_6_0", cov_hlsl, vdefs)))
            rows.append((vname, vhash, -1.0, -1.0, ident))
            for ti, t in enumerate(SHARPEN_THRESHOLDS):
                for wi, w in enumerate(SHARPEN_WIDTHS):
                    ident = "kCov_%s_t%d_w%d" % (vname, ti, wi)
                    defs = vdefs + ["SHARPEN=1", "SHARPEN_THRESHOLD=%r" % t, "SHARPEN_WIDTH=%r" % w]
                    f.write(array(ident, compile_shader("cov_%s_t%d_w%d" % (vname, ti, wi), "ps_6_0", cov_hlsl, defs)))
                    rows.append((vname, vhash, t, w, ident))
        f.write("\nstruct CoverageShader {\n    const char* variant;\n    unsigned long long gameHash;\n"
                "    float threshold;   // < 0: raw coverage\n    float width;\n"
                "    const unsigned char* bytes;\n    unsigned long long size;\n};\n\n")
        f.write("static const CoverageShader kCoverageShaders[] = {\n")
        for vname, vhash, t, w, ident in rows:
            f.write('    {"%s", 0x%016xull, %.2ff, %.2ff, %s, sizeof(%s)},\n' % (vname, vhash, t, w, ident, ident))
        f.write("};\n")
    # default config, embedded so the DLL can write it when hairfix.ini is missing
    ini = open(os.path.join(ROOT, "config", "hairfix.ini"), "rb").read() + b"\0"
    with open(os.path.join(GEN, "default_ini.h"), "w") as f:
        f.write("// generated from config/hairfix.ini\n")
        f.write("static const char kDefaultIni[] = {%s};\n" % ",".join(str(b) for b in ini))
    print("generated %d coverage shaders, %d compute shaders" % (len(rows), len(COMPUTE)))


main()
